import { parse } from "csv-parse/sync";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const csv = fs.readFileSync(path.join(__dirname, "AusterityWiki.csv"), 'utf8');

// Use synchronous parsing
const table = parse(csv, {
  columns: h => h.map(c => c.toLowerCase())
});
const rows = table.reduce((o, row) => {
  const name = row.name.replace(/[ ']/g, "");
  if (o[name]) {
    throw new Error(`${row.name} overlaps with ${o[name].name}`);
  }
  o[name] = row;
  return o;
}, {});

console.log("// This file was generated by generateCardsTable.js ");
console.log("// prettier-ignore");
console.log("export default ");
// Use a custom replacer to preserve \r\n in text fields
const jsonString = JSON.stringify(rows, (key, value) => {
  if (typeof value === 'string' && value.includes('\n')) {
    // Replace \n with \r\n to preserve Windows line endings
    return value.replace(/\n/g, '\r\n');
  }
  return value;
}, 2);
console.log(jsonString);
console.log(";");
